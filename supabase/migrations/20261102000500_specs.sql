-- SPEC is an independent entity with append-only full structured revisions.
create table roster.specs (
 id integer generated by default as identity primary key,
 workspace_id uuid not null references roster.workspaces(id),team_id uuid not null,
 number integer not null check(number>0),current_revision integer not null check(current_revision>0),
 created_at timestamptz not null default clock_timestamp(),updated_at timestamptz not null default clock_timestamp(),
 unique(workspace_id,number),unique(workspace_id,id),
 foreign key(workspace_id,team_id) references roster.teams(workspace_id,id)
);
create index specs_team on roster.specs(team_id);
create table roster.spec_revisions (
 id integer generated by default as identity primary key,spec_id integer not null references roster.specs(id),
 number integer not null check(number>0),content json not null check(json_typeof(content)='object' and octet_length(content::text)<=262144),
 message text not null default '' check(length(message)<=240 and message !~ '[[:cntrl:]]'),
 author_subject text references roster.users(subject),created_at timestamptz not null default clock_timestamp(),
 unique(spec_id,number)
);
create function roster.reject_spec_revision_mutation() returns trigger language plpgsql as $$
begin raise exception 'Spec revisions are append-only' using errcode='55000'; end $$;
create trigger spec_revisions_append_only before update or delete on roster.spec_revisions for each row execute function roster.reject_spec_revision_mutation();
create trigger spec_revisions_no_truncate before truncate on roster.spec_revisions for each statement execute function roster.reject_spec_revision_mutation();
revoke all on roster.specs,roster.spec_revisions from public,anon,authenticated;
grant select,insert,update on roster.specs to roster_app;
grant select,insert on roster.spec_revisions to roster_app;
revoke update,delete,truncate on roster.spec_revisions from roster_app;
grant usage,select on sequence roster.specs_id_seq,roster.spec_revisions_id_seq to roster_app;
